"""Validate the UTF-8 translation matrix and generate the embedded C++ catalog."""
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
header = (root / 'src/core/I18n.h').read_text(encoding='utf-8-sig')
base = {m[0]: m[1:] for m in re.findall(r'X\((\w+),\s*L"((?:[^"\\]|\\.)*)",\s*L"((?:[^"\\]|\\.)*)"\)', header)}
rows = {}
for line in (root / 'resources/i18n/translations.tsv').read_text(encoding='utf-8').splitlines():
    if not line or line.startswith('#'):
        continue
    cells = line.split('|')
    key = cells.pop(0)
    if key in rows:
        raise ValueError(f'Duplicate key: {key}')
    if cells[0].startswith('@'):
        rows[key] = cells[0]
    else:
        if len(cells) != 13 or any(not cell.strip() for cell in cells):
            raise ValueError(f'{key}: expected 13 nonempty translations, got {len(cells)}')
        rows[key] = cells
extras = {}
interface=(root / 'resources/i18n/interface.tsv').read_text(encoding='utf-8').splitlines()
extended=root/'resources/i18n/extended.tsv'
if extended.exists():
    for line in extended.read_text(encoding='utf-8').splitlines():
        if line and not line.startswith('#'):
            fields=line.split('|');key,tr,en,*translations=fields
            interface.append('|'.join((key,tr,en)))
            if key in rows:raise ValueError(f'Duplicate extended key: {key}')
            if len(translations)==1 and translations[0].startswith('@'):rows[key]=translations[0]
            elif len(translations)==13 and all(t.strip() for t in translations):rows[key]=translations
            else:raise ValueError(f'{key}: expected 13 nonempty translations')
for line in interface:
    if line and not line.startswith('#'):
        key, tr, en = line.split('|')
        if key in base or key in extras:
            raise ValueError(f'Duplicate interface key: {key}')
        extras[key] = (tr, en)
missing = (base.keys() | extras.keys()) - rows.keys()
if missing:
    raise ValueError(f'Missing translations: {sorted(missing)}')
unknown = rows.keys() - (base.keys() | extras.keys())
if unknown:
    raise ValueError(f'Unknown keys: {sorted(unknown)}')

def resolved(key, seen=None):
    seen = set() if seen is None else seen
    if key in seen:
        raise ValueError(f'Cyclic alias: {key}')
    seen.add(key)
    cells = rows[key]
    return resolved(cells[1:], seen) if isinstance(cells, str) else cells

def quote(text):
    text=text.replace('\\n','\n').replace('\\t','\t').replace('\\"','"')
    return 'L"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('\n','\\n').replace('\t','\\t') + '"'

out = ['// Generated by tools/generate_i18n.py. Edit resources/i18n/*.tsv.']
for key, (tr, en) in {**base, **extras}.items():
    translations = resolved(key)
    # printf arguments and their order must survive every translation.
    pattern = r'%(?:zu|[dius]|%)'
    expected = re.findall(pattern, en)
    for cell in translations:
        if re.findall(pattern, cell) != expected:
            raise ValueError(f'{key}: changed printf placeholders: {cell}')
    ident = f'(int)S::{key}' if key in base else '-1'
    # C++ source strings in the existing macro already contain escaped literals.
    tr = tr.replace('\\"', '"')
    en = en.replace('\\"', '"')
    out.append('{' + ident + ',{' + ','.join(map(quote, (tr, en, *translations))) + '}},')
(root / 'src/core/Translations.inc').write_text('\n'.join(out) + '\n', encoding='utf-8')
print(f'Validated {len(out)-1} messages in 15 languages; generated src/core/Translations.inc')
